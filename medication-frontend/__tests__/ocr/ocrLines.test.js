// 브라우저 OCR 결과 → 줄 요약 · 약 줄만 고르기 (서버로 나가는 글자를 정하는 곳)
//
// 고정 입력은 S2 측정(합성 처방전 36장)에서 실제로 나온 줄이다. 이름·번호는 표본용 가상값이다.
// «약 줄만 보낸다» 는 틀려도 덜 보내는 쪽으로 기울어야 한다 — 그래서 아래 «버린다» 표가
//    «보낸다» 표보다 길다. 누출 사례(성씨 «정» · «가정의학과» · 깨진 표지어 · 하이픈 없는 주민번호)는
//    전부 측정에서 실제로 새거나 샐 뻔한 모양이다.

import { describe, expect, it } from 'vitest'

import { selectDrugLines, summarizeOcrResult } from '@/lib/ocr/ocrLines'

const item = (text, confidence) => ({ text, confidence, box: { x: 0, y: 0, width: 1, height: 1 } })

describe('summarizeOcrResult', () => {
  it('신뢰도 0.5 미만 글자는 버리고, 남은 글자의 평균 신뢰도를 낸다', () => {
    const result = {
      lines: [
        [item('642200380', 0.9), item('판토복정', 0.8)],
        [item('잡음', 0.3)],
        [item('용법', 0.7)],
      ],
    }

    const { lines, meanConfidence } = summarizeOcrResult(result)

    expect(lines).toEqual(['642200380 판토복정', '용법'])
    expect(meanConfidence).toBeCloseTo((0.9 + 0.8 + 0.7) / 3)
  })

  it('남은 글자가 없으면 줄도 없고 평균 신뢰도는 0 이다', () => {
    expect(summarizeOcrResult({ lines: [[item('x', 0.1)]] })).toEqual({
      lines: [],
      meanConfidence: 0,
    })
    expect(summarizeOcrResult({ lines: [] })).toEqual({ lines: [], meanConfidence: 0 })
  })
})

describe('selectDrugLines — 보낸다', () => {
  it.each([
    ['보험코드 + 약 이름', '642200380 판토복정 40밀리그램 1 3 1'],
    ['코드와 이름이 붙어 읽힘', '643500340씨잘정(레보세티리진염산염) 1 1 3'],
    ['시럽', '642900110 코대원포르테시럽 10 3 3'],
    ['OCR 이 코드 자리를 잃음(7자리)', '4620050넥시움정20밀리그램(에스오메프라졸마그네슘삼수화물)'],
    ['코드 없는 약봉투', '타이레놀정500밀리그램'],
    ['연고', '후시딘연고 1일 2회'],
    ['용법 줄', '용법 식후30분에 복용하십시오.'],
  ])('%s', (_, line) => {
    expect(selectDrugLines([line])).toEqual([line])
  })
})

